//! Pairing secrets on disk.
//!
//! A secret lived only in memory at first, so every plugin restart forgot it and
//! the phone had to pair again. That is not a minor annoyance: re-pairing means
//! the operator has to walk to the web UI, open a window and read six digits out
//! every time the process is restarted - and a restart happens on every config
//! save and every upgrade.
//!
//! What is stored is one line per agent: its id, and the secret base64url. The
//! file is created `0600` in the plugin's own directory, beside the log. It is
//! not a credential the operator types: the phone generated it and sent it
//! inside an encrypted claim, and the file only saves us from asking for it
//! again.

use std::collections::BTreeMap;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Where the secrets live, relative to the plugin's directory.
const FILE: &str = "paired-secrets";

pub struct Store {
    path: PathBuf,
    /// The relay credential file, beside the pairing secrets.
    relay_path: PathBuf,
}

impl Store {
    /// A store rooted at the plugin's own directory.
    pub fn new(root: &Path) -> Self {
        Self {
            path: root.join(FILE),
            relay_path: root.join("relay-credentials"),
        }
    }

    /// Every stored secret, keyed by agent id.
    ///
    /// A missing file is an empty map rather than an error: a fresh install has
    /// simply never paired. An unreadable one is also empty, with a warning -
    /// refusing to start because a pairing cache is corrupt would take the
    /// plugin down over a file that only saves work.
    #[cfg(test)]
    pub fn load(&self) -> BTreeMap<String, Vec<u8>> {
        let Ok(text) = std::fs::read_to_string(&self.path) else {
            return BTreeMap::new();
        };
        let mut secrets = BTreeMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((id, encoded)) = line.split_once(' ') else {
                continue;
            };
            match crate::config::base64_url_decode(encoded.trim()) {
                Some(bytes) if bytes.len() >= 32 => {
                    secrets.insert(id.trim().to_owned(), bytes);
                }
                Some(_) => {
                    crate::log_warn!("celmux-plugin-airsim: 配对密钥长度不足，已忽略: {id}");
                }
                None => {
                    crate::log_warn!("celmux-plugin-airsim: 配对密钥不是有效 base64url: {id}");
                }
            }
        }
        secrets
    }

    /// Remember every key one agent holds, replacing whatever was there.
    ///
    /// One line per (agent, key): `<agent id> <hex-encoded device id> <key>`, and
    /// a line without the middle field is a key from before this build, filed
    /// under the empty device name. Keeping both shapes readable is what lets an
    /// upgrade leave an already-paired phone working - it was paired under a
    /// model with one key and no device name, and it keeps signing with that key
    /// until it pairs again.
    pub fn save_all(&self, id: &str, keys: &BTreeMap<String, Vec<u8>>) -> Result<(), String> {
        let mut existing = self.load_all();
        existing.insert(id.to_owned(), keys.clone());
        let mut text = String::from(
            "# AirSIM pairing secrets. One line per (agent, device): the agent id,\n\
             # the device id, then the key. A line with no device id is a key from a\n\
             # build that stored one per agent. Regenerated by pairing; delete a\n\
             # line to make that device pair again.\n",
        );
        for (agent_id, device_keys) in &existing {
            for (device, bytes) in device_keys {
                text.push_str(agent_id);
                text.push(' ');
                // The device id is a phone-chosen string that may contain spaces
                // or a newline (Android account ids do), so it is encoded rather
                // than written raw - the file is line- and space-delimited.
                text.push_str(&crate::config::base64_url_encode(device.as_bytes()));
                text.push(' ');
                text.push_str(&crate::config::base64_url_encode(bytes));
                text.push('\n');
            }
        }
        let temporary = self.path.with_extension("tmp");
        {
            let mut file = std::fs::File::create(&temporary)
                .map_err(|error| format!("无法写入配对密钥: {error}"))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = file.set_permissions(std::fs::Permissions::from_mode(0o600));
            }
            file.write_all(text.as_bytes())
                .map_err(|error| format!("无法写入配对密钥: {error}"))?;
        }
        std::fs::rename(&temporary, &self.path)
            .map_err(|error| format!("无法保存配对密钥: {error}"))
    }

    /// Every key, per agent, per device.
    ///
    /// A line is `<agent> <device> <key>`. A line whose second field is not a
    /// device id is the older one-key shape, and its key lands under the empty
    /// device name so it keeps verifying.
    pub fn load_all(&self) -> BTreeMap<String, BTreeMap<String, Vec<u8>>> {
        let Ok(text) = std::fs::read_to_string(&self.path) else {
            return BTreeMap::new();
        };
        let mut agents: BTreeMap<String, BTreeMap<String, Vec<u8>>> = BTreeMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            // Two fields is the old shape, three is the new one. Splitting on
            // whitespace cannot tell them apart when the device id is empty, so
            // the count decides which shape this line is.
            let fields: Vec<&str> = line.split_whitespace().collect();
            let (agent_id, device, encoded) = match fields.as_slice() {
                [agent, encoded] => (*agent, String::new(), *encoded),
                [agent, device, encoded] => (
                    *agent,
                    crate::config::base64_url_decode(device)
                        .and_then(|bytes| String::from_utf8(bytes).ok())
                        .unwrap_or_default(),
                    *encoded,
                ),
                _ => continue,
            };
            match crate::config::base64_url_decode(encoded) {
                Some(bytes) if bytes.len() >= 32 => {
                    agents
                        .entry(agent_id.to_owned())
                        .or_default()
                        .insert(device, bytes);
                }
                Some(_) => {
                    crate::log_warn!("celmux-plugin-airsim: 配对密钥长度不足，已忽略: {agent_id}");
                }
                None => {
                    crate::log_warn!(
                        "celmux-plugin-airsim: 配对密钥不是有效 base64url: {agent_id}"
                    );
                }
            }
        }
        agents
    }

    /// Write the phone's relay credential, `0600`, replacing any previous one.
    ///
    /// Three fields on one line: the device id, the secret, and the relay it
    /// belongs to. A credential is only valid for the relay that issued it, so
    /// the third field is what stops a leftover from being presented to a new
    /// endpoint and being refused for reasons nothing on screen explains.
    pub fn save_relay(
        &self,
        id: &str,
        relay: &crate::agents::RelayCredentials,
    ) -> Result<(), String> {
        let mut lines: Vec<String> = Vec::new();
        if let Ok(text) = std::fs::read_to_string(&self.relay_path) {
            for line in text.lines() {
                let line = line.trim();
                if line.is_empty() || line.starts_with('#') || line.starts_with(&format!("{id} ")) {
                    continue;
                }
                lines.push(line.to_owned());
            }
        }
        lines.push(format!(
            "{} {} {} {}",
            id, relay.device_id, relay.device_secret, relay.relay_url
        ));
        let text = format!(
            "# AirSIM relay credentials. One line per agent: id, device id, device secret, relay.\n{}\n",
            lines.join("\n")
        );
        let temporary = self.relay_path.with_extension("tmp");
        {
            let mut file = std::fs::File::create(&temporary)
                .map_err(|error| format!("无法写入 relay 凭据: {error}"))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = file.set_permissions(std::fs::Permissions::from_mode(0o600));
            }
            file.write_all(text.as_bytes())
                .map_err(|error| format!("无法写入 relay 凭据: {error}"))?;
        }
        std::fs::rename(&temporary, &self.relay_path)
            .map_err(|error| format!("无法保存 relay 凭据: {error}"))
    }

    /// Read back what was stored for one agent.
    pub fn load_relay(&self, id: &str) -> Option<crate::agents::RelayCredentials> {
        let text = std::fs::read_to_string(&self.relay_path).ok()?;
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut fields = line.splitn(4, ' ');
            if fields.next() != Some(id) {
                continue;
            }
            let device_id = fields.next().unwrap_or("").to_owned();
            let device_secret = fields.next().unwrap_or("").to_owned();
            let relay_url = fields.next().unwrap_or("").to_owned();
            if device_id.is_empty() || device_secret.is_empty() {
                return None;
            }
            return Some(crate::agents::RelayCredentials {
                device_id,
                device_secret,
                relay_url,
            });
        }
        None
    }

    /// Forget one agent's secret, so its next pairing starts clean.
    pub fn forget(&self, id: &str) -> Result<(), String> {
        let mut agents = self.load_all();
        if agents.remove(id).is_none() {
            return Ok(());
        }
        // Rewritten through `save_all` rather than by hand: writing the old
        // one-key shape here would silently drop every device id, and the phones
        // whose keys survived would come back unnamed after the next restart.
        let mut text = String::from(
            "# AirSIM pairing secrets. One line per (agent, device): the agent id,\n\
             # the device id, then the key. A line with no device id is a key from a\n\
             # build that stored one per agent. Regenerated by pairing; delete a\n\
             # line to make that device pair again.\n",
        );
        for (agent_id, device_keys) in &agents {
            for (device, bytes) in device_keys {
                text.push_str(agent_id);
                text.push(' ');
                text.push_str(&crate::config::base64_url_encode(device.as_bytes()));
                text.push(' ');
                text.push_str(&crate::config::base64_url_encode(bytes));
                text.push('\n');
            }
        }
        std::fs::write(&self.path, text).map_err(|error| format!("无法更新配对密钥: {error}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn directory(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("celmux-airsim-{name}"));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path).unwrap();
        path
    }

    fn keys(entries: &[(&str, [u8; 32])]) -> BTreeMap<String, Vec<u8>> {
        entries
            .iter()
            .map(|(device, key)| ((*device).to_owned(), key.to_vec()))
            .collect()
    }

    /// The whole point: keys written before a restart must be readable after
    /// one, and every phone's key has to come back - not just the newest.
    #[test]
    fn every_devices_secret_survives_a_reload() {
        let root = directory("store-roundtrip");
        let store = Store::new(&root);
        assert!(store.load_all().is_empty());
        store
            .save_all(
                "celmux-abc",
                &keys(&[("phone-a", [3_u8; 32]), ("phone-b", [4_u8; 32])]),
            )
            .unwrap();
        // A second store instance is what a restarted process has.
        let reloaded = Store::new(&root).load_all();
        let agent = reloaded.get("celmux-abc").expect("the agent is on disk");
        assert_eq!(agent.len(), 2, "both phones come back");
        assert_eq!(agent["phone-a"], vec![3_u8; 32]);
        assert_eq!(agent["phone-b"], vec![4_u8; 32]);
        let _ = std::fs::remove_dir_all(&root);
    }

    /// Saving one agent must not drop another's pairing.
    #[test]
    fn saving_one_agent_keeps_the_others() {
        let root = directory("store-multiple");
        let store = Store::new(&root);
        store.save_all("a", &keys(&[("", [1_u8; 32])])).unwrap();
        store.save_all("b", &keys(&[("", [2_u8; 32])])).unwrap();
        let agents = store.load_all();
        assert_eq!(agents.len(), 2);
        assert_eq!(agents["a"][""], vec![1_u8; 32]);
        assert_eq!(agents["b"][""], vec![2_u8; 32]);
        let _ = std::fs::remove_dir_all(&root);
    }

    /// A key filed by an older build - one line, no device id - still loads.
    ///
    /// This is the upgrade path: the phone paired when the file held a single
    /// key per agent and sent no device id. Dropping that line would make every
    /// already-paired phone pair again after an update.
    #[test]
    fn a_key_from_the_one_key_shape_still_loads() {
        let root = directory("store-legacy");
        std::fs::create_dir_all(&root).unwrap();
        let encoded = crate::config::base64_url_encode(&[9_u8; 32]);
        std::fs::write(
            root.join("paired-secrets"),
            format!("# a comment\ncelmux {encoded}\n"),
        )
        .unwrap();
        let agents = Store::new(&root).load_all();
        assert_eq!(agents["celmux"].get(""), Some(&vec![9_u8; 32]));
        let _ = std::fs::remove_dir_all(&root);
    }

    /// A device id containing a space or a newline survives the round trip.
    ///
    /// Android account ids are three lines of text joined by newlines, so the id
    /// is not safe to write into a line- and space-delimited file unchanged.
    #[test]
    fn a_device_id_with_whitespace_round_trips() {
        let root = directory("store-device-encoding");
        let store = Store::new(&root);
        let device = "com.example/.Account\nopaque-id\nUserHandle{0}";
        store
            .save_all("celmux", &keys(&[(device, [5_u8; 32])]))
            .unwrap();
        let agents = store.load_all();
        assert_eq!(
            agents["celmux"].get(device),
            Some(&vec![5_u8; 32]),
            "the encoded id decodes back to the same bytes"
        );
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn forgetting_one_agent_leaves_the_rest() {
        let root = directory("store-forget");
        let store = Store::new(&root);
        store
            .save_all("a", &keys(&[("phone-a", [1_u8; 32])]))
            .unwrap();
        store
            .save_all("b", &keys(&[("phone-b", [2_u8; 32])]))
            .unwrap();
        store.forget("a").unwrap();
        let agents = store.load_all();
        assert!(!agents.contains_key("a"));
        assert!(agents.contains_key("b"));
        let _ = std::fs::remove_dir_all(&root);
    }

    /// A truncated secret is worse than none: it would authenticate nothing and
    /// the agent would look paired while refusing every request.
    #[test]
    fn a_short_secret_is_ignored() {
        let root = directory("store-short");
        std::fs::write(
            root.join(FILE),
            format!("broken {}\n", crate::config::base64_url_encode(&[1_u8; 4])),
        )
        .unwrap();
        assert!(Store::new(&root).load().is_empty());
        let _ = std::fs::remove_dir_all(&root);
    }
}
