//! Pairing secrets on disk.
//!
//! A secret lived only in memory at first, so every plugin restart forgot it and
//! the phone had to pair again. That is not a minor annoyance: re-pairing means
//! the operator has to walk to the web UI, open a window and read six digits out
//! every time the process is restarted - and a restart happens on every config
//! save and every upgrade.
//!
//! What is stored is one line per agent: its id, and the secret base64url. The
//! file is created `0600` in the plugin's own directory, beside the log. It is
//! not a credential the operator types: the phone generated it and sent it
//! inside an encrypted claim, and the file only saves us from asking for it
//! again.

use std::collections::BTreeMap;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Where the secrets live, relative to the plugin's directory.
const FILE: &str = "paired-secrets";

pub struct Store {
    path: PathBuf,
    /// The relay credential file, beside the pairing secrets.
    relay_path: PathBuf,
}

impl Store {
    /// A store rooted at the plugin's own directory.
    pub fn new(root: &Path) -> Self {
        Self {
            path: root.join(FILE),
            relay_path: root.join("relay-credentials"),
        }
    }

    /// Every stored secret, keyed by agent id.
    ///
    /// A missing file is an empty map rather than an error: a fresh install has
    /// simply never paired. An unreadable one is also empty, with a warning -
    /// refusing to start because a pairing cache is corrupt would take the
    /// plugin down over a file that only saves work.
    pub fn load(&self) -> BTreeMap<String, Vec<u8>> {
        let Ok(text) = std::fs::read_to_string(&self.path) else {
            return BTreeMap::new();
        };
        let mut secrets = BTreeMap::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let Some((id, encoded)) = line.split_once(' ') else {
                continue;
            };
            match crate::config::base64_url_decode(encoded.trim()) {
                Some(bytes) if bytes.len() >= 32 => {
                    secrets.insert(id.trim().to_owned(), bytes);
                }
                Some(_) => {
                    crate::log_warn!("celmux-plugin-airsim: 配对密钥长度不足，已忽略: {id}");
                }
                None => {
                    crate::log_warn!("celmux-plugin-airsim: 配对密钥不是有效 base64url: {id}");
                }
            }
        }
        secrets
    }

    /// Remember the secret for one agent, replacing whatever was there.
    ///
    /// Written whole and then renamed, so a crash mid-write cannot leave a
    /// half-file that loses every other agent's pairing.
    pub fn save(&self, id: &str, secret: &[u8]) -> Result<(), String> {
        let mut secrets = self.load();
        secrets.insert(id.to_owned(), secret.to_vec());
        let mut text = String::from(
            "# AirSIM pairing secrets. One line per agent: its id, then the key.\n\
             # Regenerated by pairing; delete a line to make that agent pair again.\n",
        );
        for (agent_id, bytes) in &secrets {
            text.push_str(agent_id);
            text.push(' ');
            text.push_str(&crate::config::base64_url_encode(bytes));
            text.push('\n');
        }
        let temporary = self.path.with_extension("tmp");
        {
            let mut file = std::fs::File::create(&temporary)
                .map_err(|error| format!("无法写入配对密钥: {error}"))?;
            // Only the plugin's own user may read this: it is the key every
            // request from the phone is signed with.
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = file.set_permissions(std::fs::Permissions::from_mode(0o600));
            }
            file.write_all(text.as_bytes())
                .map_err(|error| format!("无法写入配对密钥: {error}"))?;
        }
        std::fs::rename(&temporary, &self.path)
            .map_err(|error| format!("无法保存配对密钥: {error}"))
    }

    /// Write the phone's relay credential, `0600`, replacing any previous one.
    ///
    /// Three fields on one line: the device id, the secret, and the relay it
    /// belongs to. A credential is only valid for the relay that issued it, so
    /// the third field is what stops a leftover from being presented to a new
    /// endpoint and being refused for reasons nothing on screen explains.
    pub fn save_relay(&self, id: &str, relay: &crate::agents::RelayCredentials) -> Result<(), String> {
        let mut lines: Vec<String> = Vec::new();
        if let Ok(text) = std::fs::read_to_string(&self.relay_path) {
            for line in text.lines() {
                let line = line.trim();
                if line.is_empty() || line.starts_with('#') || line.starts_with(&format!("{id} ")) {
                    continue;
                }
                lines.push(line.to_owned());
            }
        }
        lines.push(format!(
            "{} {} {} {}",
            id, relay.device_id, relay.device_secret, relay.relay_url
        ));
        let text = format!(
            "# AirSIM relay credentials. One line per agent: id, device id, device secret, relay.\n{}\n",
            lines.join("\n")
        );
        let temporary = self.relay_path.with_extension("tmp");
        {
            let mut file = std::fs::File::create(&temporary)
                .map_err(|error| format!("无法写入 relay 凭据: {error}"))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = file.set_permissions(std::fs::Permissions::from_mode(0o600));
            }
            file.write_all(text.as_bytes())
                .map_err(|error| format!("无法写入 relay 凭据: {error}"))?;
        }
        std::fs::rename(&temporary, &self.relay_path)
            .map_err(|error| format!("无法保存 relay 凭据: {error}"))
    }

    /// Read back what was stored for one agent.
    pub fn load_relay(&self, id: &str) -> Option<crate::agents::RelayCredentials> {
        let text = std::fs::read_to_string(&self.relay_path).ok()?;
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut fields = line.splitn(4, ' ');
            if fields.next() != Some(id) {
                continue;
            }
            let device_id = fields.next().unwrap_or("").to_owned();
            let device_secret = fields.next().unwrap_or("").to_owned();
            let relay_url = fields.next().unwrap_or("").to_owned();
            if device_id.is_empty() || device_secret.is_empty() {
                return None;
            }
            return Some(crate::agents::RelayCredentials {
                device_id,
                device_secret,
                relay_url,
            });
        }
        None
    }

    /// Forget one agent's secret, so its next pairing starts clean.
    pub fn forget(&self, id: &str) -> Result<(), String> {
        let mut secrets = self.load();
        if secrets.remove(id).is_none() {
            return Ok(());
        }
        let mut text = String::new();
        for (agent_id, bytes) in &secrets {
            text.push_str(agent_id);
            text.push(' ');
            text.push_str(&crate::config::base64_url_encode(bytes));
            text.push('\n');
        }
        std::fs::write(&self.path, text).map_err(|error| format!("无法更新配对密钥: {error}"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn directory(name: &str) -> PathBuf {
        let path = std::env::temp_dir().join(format!("celmux-airsim-{name}"));
        let _ = std::fs::remove_dir_all(&path);
        std::fs::create_dir_all(&path).unwrap();
        path
    }

    /// The whole point: a secret written before a restart must be readable
    /// after one.
    #[test]
    fn a_saved_secret_survives_a_reload() {
        let root = directory("store-roundtrip");
        let store = Store::new(&root);
        assert!(store.load().is_empty());
        store.save("celmux-abc", &[3_u8; 32]).unwrap();
        // A second store instance is what a restarted process has.
        let reloaded = Store::new(&root).load();
        assert_eq!(reloaded.get("celmux-abc"), Some(&vec![3_u8; 32]));
        let _ = std::fs::remove_dir_all(&root);
    }

    /// Saving one agent must not drop another's pairing.
    #[test]
    fn saving_one_agent_keeps_the_others() {
        let root = directory("store-multiple");
        let store = Store::new(&root);
        store.save("a", &[1_u8; 32]).unwrap();
        store.save("b", &[2_u8; 32]).unwrap();
        let secrets = store.load();
        assert_eq!(secrets.len(), 2);
        assert_eq!(secrets["a"], vec![1_u8; 32]);
        assert_eq!(secrets["b"], vec![2_u8; 32]);
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn forgetting_one_agent_leaves_the_rest() {
        let root = directory("store-forget");
        let store = Store::new(&root);
        store.save("a", &[1_u8; 32]).unwrap();
        store.save("b", &[2_u8; 32]).unwrap();
        store.forget("a").unwrap();
        let secrets = store.load();
        assert!(!secrets.contains_key("a"));
        assert!(secrets.contains_key("b"));
        let _ = std::fs::remove_dir_all(&root);
    }

    /// A truncated secret is worse than none: it would authenticate nothing and
    /// the agent would look paired while refusing every request.
    #[test]
    fn a_short_secret_is_ignored() {
        let root = directory("store-short");
        std::fs::write(
            root.join(FILE),
            format!("broken {}\n", crate::config::base64_url_encode(&[1_u8; 4])),
        )
        .unwrap();
        assert!(Store::new(&root).load().is_empty());
        let _ = std::fs::remove_dir_all(&root);
    }
}
